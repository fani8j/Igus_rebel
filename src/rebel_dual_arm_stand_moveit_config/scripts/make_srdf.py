#!/usr/bin/env python3
"""Generate config/rebel_dual_arm.srdf from the expanded rebel_dual_arm URDF.

  source install/setup.bash
  python3 scripts/make_srdf.py --out config/rebel_dual_arm.srdf

Disabled collision pairs are CONSERVATIVE (no sampling):
  * Adjacent : every pair of links joined by a joint (parent/child), as the MoveIt Setup Assistant does;
  * Adjacent : all collision-bearing tool links of one arm among each other (they are rigid on link6; link6 itself is the parent of each);
  * Never/Adjacent: the arm-internal pairs of OUR single-arm SRDF (src/igus_rebel_moveit_config/config/igus_rebel2.srdf, a Setup-Assistant
    sampling result for the same arm links), prefixed per arm; tool and rig links are NOT covered by it;
  * Adjacent : the head-camera parts among themselves (all fixed on `stand`, overlapping placeholder boxes).
Deliberately ENABLED (as in compal_robot): stand <-> slider_* (slider travel into the centre triangle support), slider_left <-> slider_right,
arm <-> arm, tool <-> other arm, tool <-> link5/link4 etc.
"""
import argparse
import itertools
import os
import subprocess
import xml.etree.ElementTree as ET

HOME_LIFT = -0.2
SLIDER_IN = 0.005973        # (0.459946 - 0.448) / 2 : arm spacing s = 0.448 m
ARM_LINKS = ['base_link', 'motor1', 'link1', 'motor2', 'link2', 'motor3', 'link3', 'motor4', 'link4', 'motor5', 'link5', 'link6']
SINGLE_ARM_SRDF = '/home/farhan/igus_rebel_ros2/src/igus_rebel_moveit_config/config/igus_rebel2.srdf'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--out', required=True)
    ap.add_argument('--single-arm-srdf', default=SINGLE_ARM_SRDF)
    a = ap.parse_args()
    from ament_index_python.packages import get_package_share_directory
    xacro_file = os.path.join(get_package_share_directory('rebel_dual_arm_stand_description'), 'urdf', 'rebel_dual_arm.urdf.xacro')
    urdf = ET.fromstring(subprocess.run(['xacro', xacro_file, 'hardware_protocol:=mock_hardware'], check=True, capture_output=True, text=True).stdout)
    links = {l.get('name'): l for l in urdf.findall('link')}
    joints = urdf.findall('joint')
    has_col = {n for n, l in links.items() if l.findall('collision')}

    disabled = {}

    def dis(x, y, why):
        if x != y and x in links and y in links:
            disabled.setdefault(frozenset((x, y)), why)

    for j in joints:
        dis(j.find('parent').get('link'), j.find('child').get('link'), 'Adjacent')
    stand_parts = ['stand', 'camera_riser', 'camera_boom', 'gemini336L_camera_link']
    for x, y in itertools.combinations(stand_parts, 2):
        dis(x, y, 'Adjacent')
    tool_names = []
    for arm in ('arm_left_', 'arm_right_'):
        tool = [n for n in has_col if n.startswith(arm) and n.split(arm, 1)[1] not in ARM_LINKS]
        tool_names.append(tool)
        for x, y in itertools.combinations(tool + [arm + 'link6'], 2):
            dis(x, y, 'Adjacent')
        sroot = ET.parse(a.single_arm_srdf).getroot()
        for dc in sroot.findall('disable_collisions'):
            x, y = dc.get('link1'), dc.get('link2')
            if x in ARM_LINKS and y in ARM_LINKS:
                dis(arm + x, arm + y, dc.get('reason'))

    srdf = ET.Element('robot', name='rebel_dual_arm')
    srdf.append(ET.Comment(
        ' Generated by scripts/make_srdf.py (group structure and the rig Adjacent pairs follow compal_robot dual_arm_rig.srdf @ bb76327, MIT, see NOTICE). '
        'Collision matrix is conservative: Adjacent/rigid pairs and our single-arm SRDF pairs only, no sampled "Never" pairs. '))
    g = ET.SubElement(srdf, 'group', name='gantry')
    for jn in ('lift_joint', 'slider_left_joint', 'slider_right_joint'):
        ET.SubElement(g, 'joint', name=jn)
    for arm, side in (('arm_left', 'left'), ('arm_right', 'right')):
        g = ET.SubElement(srdf, 'group', name=arm)
        ET.SubElement(g, 'chain', base_link=arm + '_base_link', tip_link=arm + '_knife_tip')
    g = ET.SubElement(srdf, 'group', name='dual_arm')
    for sub in ('gantry', 'arm_left', 'arm_right'):
        ET.SubElement(g, 'group', name=sub)
    for arm, tool in zip(('arm_left', 'arm_right'), tool_names):
        g = ET.SubElement(srdf, 'group', name=arm + '_tool')
        for n in sorted(tool):
            ET.SubElement(g, 'link', name=n)
    for arm in ('arm_left', 'arm_right'):
        ET.SubElement(srdf, 'end_effector', name=arm + '_tool', parent_link=arm + '_link6', group=arm + '_tool', parent_group=arm)

    def state(group, vals):
        gs = ET.SubElement(srdf, 'group_state', name='home', group=group)
        for k, v in vals:
            ET.SubElement(gs, 'joint', name=k, value=repr(v) if isinstance(v, float) else str(v))
    gantry = [('lift_joint', HOME_LIFT), ('slider_left_joint', -SLIDER_IN), ('slider_right_joint', SLIDER_IN)]
    left = [('arm_left_joint%d' % i, 0.0) for i in range(1, 7)]
    right = [('arm_right_joint%d' % i, 0.0) for i in range(1, 7)]
    state('gantry', gantry)
    state('arm_left', left)
    state('arm_right', right)
    state('dual_arm', gantry + left + right)

    for key in sorted(disabled, key=lambda k: tuple(sorted(k))):
        x, y = sorted(key)
        ET.SubElement(srdf, 'disable_collisions', link1=x, link2=y, reason=disabled[key])
    ET.indent(srdf, space='  ')
    ET.ElementTree(srdf).write(a.out, xml_declaration=True, encoding='utf-8')
    print('wrote', a.out, 'disabled pairs:', len(disabled), 'collision links:', len(has_col))


if __name__ == '__main__':
    main()
