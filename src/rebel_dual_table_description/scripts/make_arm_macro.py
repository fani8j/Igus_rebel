#!/usr/bin/env python3
"""Generate urdf/rebel_arm.macro.xacro from igus_rebel_description/urdf/igus_rebel2.urdf.

    python3 scripts/make_arm_macro.py [--single <igus_rebel2.urdf>] [--out urdf/rebel_arm.macro.xacro]
    python3 scripts/make_arm_macro.py --check          # exit 1 if the checked-in macro is stale

Every link and joint name (and every parent/child reference) gets the ${prefix} in front; limits,
inertials and visuals are copied verbatim, so FK is the single-arm FK by construction. Collisions are copied
verbatim EXCEPT the links in DUAL_COLLISION_OVERRIDES below. Run it again whenever igus_rebel2.urdf or the
override table changes (the pytest fails otherwise).
"""
import argparse
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_SINGLE = os.path.normpath(os.path.join(
    HERE, "..", "..", "igus_rebel_description", "urdf", "igus_rebel2.urdf"))
DEFAULT_OUT = os.path.normpath(os.path.join(HERE, "..", "urdf", "rebel_arm.macro.xacro"))

# DUAL-ARM-ONLY collision override table: link name (without prefix) -> collision meshes (package:// URIs,
# link frame, identity origin; the visual origin is baked into the STLs). They REPLACE the <collision> of that link
# in the generated macro; the single-arm model (igus_rebel2.urdf, the real robot) is NOT changed.
# Why: the single-arm box/cylinder primitives of link1-4 (and, by up to 20 mm, motor3) do not contain the real link
# meshes (up to 88 mm of the real surface lies outside them), which is not acceptable when the model is used to
# prove that two arms moving at the same time cannot collide. The meshes are conservative convex hulls (one hull,
# or a few convex pieces for the L-shaped links) of the real meshes, generated and verified by
# scripts/make_collision_hulls.py (meshes/collision/README.md). link5 is not listed: igus_rebel2.urdf already uses
# a hull of its real mesh. scripts/check_fk_equivalence.py and the pytest require that exactly these links differ
# from the single arm and that they use exactly these meshes.
_P = "package://rebel_dual_table_description/meshes/collision/"
DUAL_COLLISION_OVERRIDES = {
    "base_link": [_P + "base_link_hull.stl"],
    "motor1": [_P + "motor1_hull.stl"],
    "link1": [_P + "link1_hull_1.stl", _P + "link1_hull_2.stl"],
    "motor2": [_P + "motor2_hull.stl"],
    "link2": [_P + "link2_hull_1.stl", _P + "link2_hull_2.stl", _P + "link2_hull_3.stl"],
    "motor3": [_P + "motor3_hull.stl"],
    "link3": [_P + "link3_hull_1.stl", _P + "link3_hull_2.stl"],
    "motor4": [_P + "motor4_hull.stl"],
    "link4": [_P + "link4_hull_1.stl", _P + "link4_hull_2.stl"],
    "motor5": [_P + "motor5_hull.stl"],
    "link6": [_P + "link6_hull.stl"],
}

HEADER = """<?xml version="1.0"?>
<!-- Prefixed ReBeL arm for the dual-arm test table.
     GENERATED by scripts/make_arm_macro.py from igus_rebel_description/urdf/igus_rebel2.urdf: every
     link and joint is renamed to ${prefix}<name>; limits, inertials and visuals are copied verbatim, so FK
     is identical to the single-arm model. Collisions are copied verbatim EXCEPT the links of
     DUAL_COLLISION_OVERRIDES (make_arm_macro.py), which use conservative convex hulls of the real link
     meshes (meshes/collision/). See scripts/check_fk_equivalence.py. Do not hand-edit; re-generate when
     igus_rebel2.urdf or the override table changes.
-->
<robot xmlns:xacro="http://www.ros.org/wiki/xacro">
  <!-- prefix: e.g. "arm_left_"; parent: link the base is attached to; xyz/rpy: "x y z" / "r p y" strings. -->
  <xacro:macro name="rebel_arm" params="prefix parent xyz rpy">
    <joint name="${prefix}base_joint" type="fixed">
      <parent link="${parent}"/>
      <child link="${prefix}base_link"/>
      <origin xyz="${xyz}" rpy="${rpy}"/>
    </joint>
"""
FOOTER = """  </xacro:macro>
</robot>
"""


def collision_block(meshes):
    # indentation is relative to the raw single-arm URDF body (the whole body is indented by 2 afterwards)
    out = ["<!-- DUAL-ONLY collision: convex hull(s) of the real link mesh (scripts/make_collision_hulls.py),"
           " replaces the single-arm primitive. -->"]
    for m in meshes:
        out.append("<collision>\n"
                   "      <origin\n"
                   "        xyz=\"0 0 0\"\n"
                   "        rpy=\"0 0 0\" />\n"
                   "      <geometry>\n"
                   "        <mesh\n"
                   f"          filename=\"{m}\" />\n"
                   "      </geometry>\n"
                   "    </collision>")
    return "\n    ".join(out)


def apply_collision_overrides(body):
    """Replace the single <collision> of every link in DUAL_COLLISION_OVERRIDES (body is already prefixed)."""
    done = set()

    def repl(m):
        name = m.group(1)
        if name not in DUAL_COLLISION_OVERRIDES:
            return m.group(0)
        block = m.group(0)
        n = len(re.findall(r"<collision>", block))
        if n != 1:
            raise SystemExit(f"link {name}: expected exactly one <collision> in the single-arm URDF, found {n}")
        done.add(name)
        return re.sub(r"<collision>.*?</collision>",
                      lambda _: collision_block(DUAL_COLLISION_OVERRIDES[name]), block, count=1, flags=re.S)

    body = re.sub(r'<link\s+name\s*=\s*"\$\{prefix\}([^"]+)">.*?</link>', repl, body, flags=re.S)
    missing = set(DUAL_COLLISION_OVERRIDES) - done
    if missing:
        raise SystemExit(f"override table names links that do not exist in the single-arm URDF: {sorted(missing)}")
    return body


def generate(single_path):
    text = open(single_path).read()
    m = re.search(r"<robot\b[^>]*>(.*)</robot>", text, flags=re.S)
    if not m:
        raise SystemExit(f"{single_path}: no <robot> element")
    body = m.group(1)
    n_before = len(re.findall(r"<(?:link|joint)\b", body))
    # prefix link/joint names and parent/child references (attributes may sit on the next line)
    body, n1 = re.subn(r'(<(?:link|joint)\s+name\s*=\s*")([^"]+)"', r'\1${prefix}\2"', body)
    body, n2 = re.subn(r'(<(?:parent|child)\s+link\s*=\s*")([^"]+)"', r'\1${prefix}\2"', body)
    if n1 != n_before:
        raise SystemExit(f"renamed {n1} link/joint names but found {n_before} elements")
    if re.search(r"<(?:mimic|transmission|gazebo)\b|<material\b", body):
        raise SystemExit("igus_rebel2.urdf has elements this generator does not prefix; extend it")
    body = apply_collision_overrides(body)
    body = body.strip("\n")
    # drop the single-arm joint-limit header comment from the body, keep it as a macro comment
    body = "\n".join("  " + ln if ln.strip() else ln for ln in body.split("\n"))
    return HEADER + "\n" + body + "\n" + FOOTER


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--single", default=DEFAULT_SINGLE)
    ap.add_argument("--out", default=DEFAULT_OUT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    new = generate(a.single)
    if a.check:
        old = open(a.out).read() if os.path.exists(a.out) else ""
        if old != new:
            print(f"{a.out} is STALE: re-run scripts/make_arm_macro.py", file=sys.stderr)
            return 1
        print("rebel_arm.macro.xacro is up to date")
        return 0
    with open(a.out, "w") as f:
        f.write(new)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
